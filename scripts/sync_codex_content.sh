#!/usr/bin/env bash
# Linux/macOS counterpart to sync_codex_content.ps1.
#
# Mirrors the Areshnaat vault into content/ and regenerates derived JSON.
# Unlike the PowerShell version (robocopy /MIR) this is ADDITIVE BY DEFAULT:
# the vault and content/ have drifted apart before, and an unguarded mirror
# would delete notes that exist only on one side. Pass --mirror for true
# mirror semantics; it dry-runs and asks before deleting anything.
#
#   ./scripts/sync_codex_content.sh                  # additive
#   ./scripts/sync_codex_content.sh --mirror         # mirror, with confirmation
#   ./scripts/sync_codex_content.sh --mirror --yes   # mirror, no prompt (CI)
#   ./scripts/sync_codex_content.sh --dry-run        # show, change nothing
#   ARESH_CODEX_SOURCE=/path/to/vault ./scripts/sync_codex_content.sh
#
# Notes with `publish: false` in their frontmatter are held back regardless of
# mode; see scripts/publish_gate.mjs.

set -euo pipefail

# Resolve the repo to sync INTO. Prefer the git worktree the caller is standing
# in, so `bash /path/to/areshatlas-site/scripts/sync_codex_content.sh` run from a
# second worktree targets that worktree rather than the script's own checkout.
# Falls back to the script's location when cwd is not a usable checkout.
script_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
repo_root="$script_root"
if cwd_root="$(git rev-parse --show-toplevel 2>/dev/null)" \
   && [ -n "$cwd_root" ] \
   && [ -f "$cwd_root/codex_registry/publish.json" ] \
   && [ -d "$cwd_root/content" ] \
   && [ "$cwd_root" != "$script_root" ]; then
  repo_root="$cwd_root"
  echo "[codex-sync] note: syncing the checkout you are in ($repo_root),"
  echo "[codex-sync]       not the one this script lives in ($script_root)."
fi
registry="$repo_root/codex_registry/publish.json"
dest="$repo_root/content"

mirror=0; assume_yes=0; dry_run=0
for arg in "$@"; do
  case "$arg" in
    --mirror)  mirror=1 ;;
    --yes|-y)  assume_yes=1 ;;
    --dry-run) dry_run=1 ;;
    -h|--help) sed -n '2,16p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "[codex-sync] unknown argument: $arg" >&2; exit 2 ;;
  esac
done

command -v rsync >/dev/null || { echo "[codex-sync] rsync not found" >&2; exit 1; }
command -v node  >/dev/null || { echo "[codex-sync] node not found"  >&2; exit 1; }
[ -f "$registry" ] || { echo "[codex-sync] missing $registry" >&2; exit 1; }

# Source: env override, else the registry default (with ~ expanded).
source_dir="${ARESH_CODEX_SOURCE:-}"
if [ -z "$source_dir" ]; then
  source_dir="$(node -p "require('$registry').source_default" 2>/dev/null || true)"
  source_dir="${source_dir/#\~/$HOME}"
fi
[ -n "$source_dir" ] || { echo "[codex-sync] no source configured" >&2; exit 1; }
[ -d "$source_dir" ] || { echo "[codex-sync] source vault not found: $source_dir" >&2; exit 1; }

readarray -t sections < <(node -p "require('$registry').sections.join('\n')")
readarray -t assets   < <(node -p "require('$registry').assets.join('\n')")
readarray -t guards   < <(node -p "require('$registry').never_publish.join('\n')")

echo "[codex-sync] source: $source_dir"
echo "[codex-sync] dest:   $dest"
echo "[codex-sync] mode:   $([ "$mirror" = 1 ] && echo mirror || echo additive)$([ "$dry_run" = 1 ] && echo ' (dry-run)')"

mkdir -p "$dest"

rsync_base=(rsync -a --human-readable --itemize-changes)
for g in "${guards[@]}"; do [ -n "$g" ] && rsync_base+=(--exclude "$g"); done
# content/_derived is generated by this script, never sourced from the vault.
rsync_base+=(--filter 'protect _derived/***')
# An empty note has nothing to publish: it would land as a live URL with no
# heading and a title built from the raw filename. Leave placeholders in the
# vault, keep them out of the site.
rsync_base+=(--min-size=1)
[ "$dry_run" = 1 ] && rsync_base+=(--dry-run)

# --- per-note publish gate ----------------------------------------------------
# The allowlist above is path-based; this is the per-note switch. A note with
# `publish: false` in its frontmatter (a checkbox in Obsidian's Properties
# panel) never enters content/, so it is not in the public repo either.
gate_list="$(mktemp)"
gate_section="$(mktemp)"
trap 'rm -f "$gate_list" "$gate_section"' EXIT
node "$script_root/scripts/publish_gate.mjs" --root "$repo_root" --source "$source_dir" --list > "$gate_list"
gate_held=$(wc -l < "$gate_list")
[ "$gate_held" -gt 0 ] && printf '[codex-sync]   gate: %s note(s) held back by publish: false\n' "$gate_held"

# --- mirror confirmation ------------------------------------------------------
if [ "$mirror" = 1 ] && [ "$assume_yes" != 1 ] && [ "$dry_run" != 1 ]; then
  echo
  echo "[codex-sync] --mirror will DELETE files in content/ that are absent from the vault."
  echo "[codex-sync] dry run of deletions:"
  deletions=0
  for d in "${sections[@]}" "${assets[@]}"; do
    [ -n "$d" ] && [ -d "$source_dir/$d" ] && [ -d "$dest/$d" ] || continue
    out="$("${rsync_base[@]}" --dry-run --delete "$source_dir/$d/" "$dest/$d/" | grep '^\*deleting' || true)"
    if [ -n "$out" ]; then echo "$out" | sed 's/^/    /'; deletions=$((deletions + $(echo "$out" | wc -l))); fi
  done
  if [ "$deletions" = 0 ]; then
    echo "    (none)"
  else
    echo
    printf '[codex-sync] delete %s file(s)? [y/N] ' "$deletions"
    read -r reply </dev/tty || reply=n
    case "$reply" in [yY]*) ;; *) echo "[codex-sync] aborted"; exit 1 ;; esac
  fi
fi

[ "$mirror" = 1 ] && rsync_base+=(--delete)

# --- sections and assets ------------------------------------------------------
for d in "${sections[@]}" "${assets[@]}"; do
  [ -n "$d" ] || continue
  if [ ! -d "$source_dir/$d" ]; then
    printf '[codex-sync]   skip %-14s (not in vault)\n' "$d"
    continue
  fi
  mkdir -p "$dest/$d"
  printf '[codex-sync]   sync %s\n' "$d"
  # Anchored with a leading / so each pattern resolves against this section
  # rather than matching the same basename anywhere in the tree.
  sed -n "s|^$d/|/|p" "$gate_list" > "$gate_section"
  "${rsync_base[@]}" --exclude-from="$gate_section" "$source_dir/$d/" "$dest/$d/" | sed 's/^/    /'
done

# --- loose root assets (never with --delete: content/ root holds other files) --
globs=()
while IFS= read -r g; do [ -n "$g" ] && globs+=(--include "$g"); done \
  < <(node -p "require('$registry').root_file_globs.join('\n')")
if [ "${#globs[@]}" -gt 0 ]; then
  echo "[codex-sync]   sync (root assets)"
  root_cmd=(rsync -a --human-readable --itemize-changes --exclude '*/' "${globs[@]}" --exclude '*')
  [ "$dry_run" = 1 ] && root_cmd+=(--dry-run)
  "${root_cmd[@]}" "$source_dir/" "$dest/" | sed 's/^/    /'
fi

# --- unpublish notes whose box was unticked after they went live --------------
# Additive sync never deletes, so a note flipped to `publish: false` would keep
# its stale copy in content/ (and on the site) forever.
if [ "$dry_run" = 1 ]; then
  node "$script_root/scripts/publish_gate.mjs" --root "$repo_root" --source "$source_dir" --prune --dry-run | sed 's/^/    /'
else
  node "$script_root/scripts/publish_gate.mjs" --root "$repo_root" --source "$source_dir" --prune | sed 's/^/    /'
fi

# --- scrub vault-only material ------------------------------------------------
# The vault keeps DM/private blocks; the published copy must not. This runs
# BEFORE derive so the derived json never indexes private text either.
if [ "$dry_run" = 1 ]; then
  echo "[codex-sync] dry run: skipping scrub"
  node "$script_root/scripts/scrub_private.mjs" --root "$repo_root" --dry-run | sed 's/^/    /'
else
  node "$script_root/scripts/scrub_private.mjs" --root "$repo_root" | sed 's/^/    /'
fi

# --- record page history ------------------------------------------------------
# After the scrub, so a stored revision can never hold DM material, and before
# derive, which only reads the current text. The previous entry in the store is
# the file this sync replaced.
if [ "$dry_run" = 1 ]; then
  node "$script_root/scripts/build_history.mjs" --root "$repo_root" --capture --dry-run | sed 's/^/    /'
else
  node "$script_root/scripts/build_history.mjs" --root "$repo_root" --capture | sed 's/^/    /'
fi

# --- derive -------------------------------------------------------------------
if [ "$dry_run" = 1 ]; then
  echo "[codex-sync] dry run: skipping derive"
else
  echo "[codex-sync] generating derived sidebar/navbox json..."
  ( cd "$repo_root" && node ./scripts/generate_codex_derived.mjs )
fi

echo "[codex-sync] done"
